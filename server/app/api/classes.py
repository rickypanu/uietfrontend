from typing import Optional

from bson import ObjectId
from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, Field

from app.core.security import current_teacher, own_teacher
from app.core.subjects import is_valid_class, normalize_branch, normalize_course, subjects_for
from app.db.database import approved_students, attendance, classes, otps
from app.utils.classmatch import otp_matches_class
from app.utils.helpers import ci, percentage, semester_values
from app.utils.timeutils import (
    month_bounds_utc, parse_any_datetime, parse_iso_date, range_bounds_utc, to_ist, to_ist_iso, utcnow,
)

router = APIRouter(prefix="/classes", tags=["Classes"])


class ClassCreate(BaseModel):
    department: str = Field(min_length=1, max_length=60)
    course: str
    branch: str
    section: str = Field(min_length=1, max_length=2)
    semester: int
    subject: str


def serialize_class(c: dict) -> dict:
    return {
        "id": str(c.get("_id")),
        "teacher_id": c.get("teacher_id", ""),
        "department": c.get("department", ""),
        "course": c.get("course", ""),
        "branch": c.get("branch", ""),
        "section": c.get("section", ""),
        "semester": c.get("semester"),
        "subject": c.get("subject", ""),
        "created_at": to_ist_iso(parse_any_datetime(c.get("created_at"))),
    }


def _own_class(class_id: str, teacher_id: str) -> dict:
    # Class ids are stored as plain strings (str(ObjectId())) - keep that for existing data.
    class_doc = classes.find_one({"_id": class_id})
    if not class_doc:
        raise HTTPException(404, "Class not found")
    if str(class_doc.get("teacher_id", "")).upper() != teacher_id.upper():
        raise HTTPException(403, "This class belongs to another teacher")
    return class_doc


@router.post("/create", status_code=201)
def create_class(data: ClassCreate, teacher_id: str = Depends(current_teacher)):
    course, branch = normalize_course(data.course), normalize_branch(data.branch)
    if not is_valid_class(course, branch, data.semester):
        raise HTTPException(400, "Invalid course / branch / semester")
    if data.subject not in subjects_for(course, branch, data.semester):
        raise HTTPException(400, "This subject is not part of the selected course / branch / semester")
    section = data.section.strip().upper()
    if not section.isalnum():
        raise HTTPException(400, "Section must be letters or digits")

    duplicate = classes.find_one({
        "teacher_id": teacher_id, "course": course, "branch": branch,
        "section": section, "semester": data.semester, "subject": data.subject,
    }, {"_id": 1})
    if duplicate:
        raise HTTPException(409, "You already created this class")

    doc = {
        "_id": str(ObjectId()),
        "teacher_id": teacher_id,
        "department": data.department.strip().upper(),
        "course": course, "branch": branch, "section": section,
        "semester": data.semester, "subject": data.subject,
        "created_at": utcnow(),
    }
    classes.insert_one(doc)
    return serialize_class(doc)


@router.get("/list/{employee_id}")
def list_classes(employee_id: str = Depends(own_teacher)):
    return [serialize_class(c) for c in classes.find({"teacher_id": employee_id}).sort("created_at", -1)]


@router.get("/register/{class_id}")
def get_class_register(
    class_id: str,
    month: Optional[int] = Query(None, ge=1, le=12),
    year: Optional[int] = Query(None, ge=2000, le=2100),
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    teacher_id: str = Depends(current_teacher),
):
    """Attendance register for one class: one column per lecture (OTP), one row per student."""
    class_doc = _own_class(class_id, teacher_id)

    # --- period -------------------------------------------------------------------------
    period = None
    try:
        if month and year:
            period = month_bounds_utc(year, month)
        elif start_date and end_date:
            period = range_bounds_utc(parse_iso_date(start_date), parse_iso_date(end_date))
    except ValueError as exc:
        raise HTTPException(400, str(exc))

    # --- lectures (OTPs generated by this teacher for this class) -----------------------
    otp_query = {
        "teacher_id": class_doc["teacher_id"],
        "subject": ci(class_doc["subject"]),
        "branch": ci(class_doc["branch"]),
        "semester": {"$in": semester_values(class_doc["semester"])},
    }
    if period:
        otp_query["start_time"] = {"$gte": period[0], "$lt": period[1]}

    lectures = []
    for o in otps.find(otp_query, {"otp": 1, "start_time": 1, "subject": 1, "branch": 1, "semester": 1, "course": 1, "section": 1}).sort("start_time", 1):
        if not otp_matches_class(o, class_doc):  # applies the optional course / section rules
            continue
        start = to_ist(parse_any_datetime(o["start_time"]))
        lectures.append({
            "key": o["otp"],                                   # unique even when two lectures happen on one day
            "date": start.date().isoformat(),
            "time": start.strftime("%H:%M"),
            "label": start.strftime("%d %b"),
        })

    # --- students & marks ---------------------------------------------------------------
    students = list(approved_students.find(
        {
            "course": ci(class_doc["course"]), "branch": ci(class_doc["branch"]),
            "section": ci(class_doc["section"]), "semester": {"$in": semester_values(class_doc["semester"])},
        },
        {"_id": 0, "roll_no": 1, "full_name": 1},
    ).sort("roll_no", 1))

    codes = [lec["key"] for lec in lectures]
    present = set()
    if codes:
        for r in attendance.find({"otp": {"$in": codes}}, {"roll_no": 1, "otp": 1, "_id": 0}):
            present.add((r["roll_no"], r["otp"]))

    rows = []
    for s in students:
        marks = {lec["key"]: ("P" if (s["roll_no"], lec["key"]) in present else "A") for lec in lectures}
        total_present = sum(1 for m in marks.values() if m == "P")
        rows.append({
            "roll_no": s["roll_no"],
            "name": s.get("full_name", ""),
            "marks": marks,
            "present": total_present,
            "total": len(lectures),
            "percentage": percentage(total_present, len(lectures)),
        })

    info = {k: class_doc.get(k) for k in ("department", "course", "branch", "semester", "section", "subject")}
    return {"class_info": info, "lectures": lectures, "students": rows}


@router.delete("/{class_id}")
def delete_class(class_id: str, teacher_id: str = Depends(current_teacher)):
    """Removes the class entry only. OTPs and attendance records are kept for the audit trail."""
    class_doc = _own_class(class_id, teacher_id)
    classes.delete_one({"_id": class_doc["_id"]})
    return {"message": "Class deleted. Past attendance records were kept."}
